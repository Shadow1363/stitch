/**
 * Installable PWA: the single-file page plus a web manifest, icons and a service worker that
 * caches them, so the game installs and runs offline once loaded over HTTPS (or localhost).
 */
import { LETTERBOX } from '@stitch/runtime';
import { slug, type ExportedGame } from './game';
import { exportHtml } from './html';

export interface PwaIcons {
  /** PNG bytes, square. */
  192: Uint8Array;
  512: Uint8Array;
}

/** File path -> contents, ready to zip or serve from one folder. */
export type FileSet = Record<string, string | Uint8Array>;

export function pwaFiles(game: ExportedGame, playerJs: string, icons: PwaIcons): FileSet {
  const id = slug(game.title);
  const manifest = {
    name: game.title,
    short_name: game.title.length > 12 ? game.title.slice(0, 12).trim() : game.title,
    ...(game.author ? { description: `${game.title} by ${game.author}` } : {}),
    id: './',
    start_url: './',
    scope: './',
    display: 'fullscreen',
    orientation: game.stage.width >= game.stage.height ? 'landscape' : 'portrait',
    background_color: LETTERBOX,
    theme_color: LETTERBOX,
    icons: [
      { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
    ],
  };
  const html = exportHtml(game, playerJs, {
    target: 'pwa',
    head: [
      '<link rel="manifest" href="manifest.webmanifest" />',
      '<link rel="icon" href="icon-192.png" />',
      '<link rel="apple-touch-icon" href="icon-192.png" />',
      `<meta name="theme-color" content="${LETTERBOX}" />`,
    ].join('\n    '),
    // Service workers need http(s); opened from disk the page still runs, just not offline-installed.
    script:
      "if ('serviceWorker' in navigator && location.protocol !== 'file:') navigator.serviceWorker.register('./sw.js');",
  });
  const files: FileSet = {
    'index.html': html,
    'manifest.webmanifest': JSON.stringify(manifest, null, 2) + '\n',
    'icon-192.png': icons[192],
    'icon-512.png': icons[512],
  };
  // The cache name changes with the content, so an updated export replaces the old cache.
  const version = hash(html + files['manifest.webmanifest']);
  files['sw.js'] = serviceWorker(`stitch-${id}-`, version, ['./', ...Object.keys(files)]);
  return files;
}

function serviceWorker(prefix: string, version: string, files: string[]): string {
  return `// Generated by Stitch. Caches the game for offline play; requests to other origins (APIs) pass through.
const PREFIX = ${JSON.stringify(prefix)};
const CACHE = PREFIX + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then((c) => c.match(e.request, { ignoreSearch: true })).then((hit) => hit || fetch(e.request)));
});
`;
}

/** FNV-1a, 32-bit, as hex. Enough to tell one export from the next. */
export function hash(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, '0');
}
