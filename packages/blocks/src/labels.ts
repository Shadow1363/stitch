/** Block text for any catalog entry: extensions carry their own label. */
export const labelOf = (b: Builtin): string => b.ext?.label ?? BUILTIN_LABELS[b.name] ?? b.name;

/** Toolbox starting value for parameter `i`. */
export const defaultOf = (b: Builtin, i: number): number | string | undefined =>
  b.ext ? b.ext.defaults[i] : TOOLBOX_DEFAULTS[b.name]?.[i];

export const blockTypeOf = (b: Builtin) => `stitch_${b.kind === 'command' ? 'b' : 'r'}_${b.name}`;
